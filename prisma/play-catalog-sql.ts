import {
  BOT_GROUP,
  BOT_GROUP_LABELS,
  BOT_GROUP_LISTED,
  BOT_GROUP_RING,
  GAME_TERMINATION,
  GAME_TERMINATION_LABELS,
  TIME_CONTROL_VALUES,
} from "../constants/platform/play-codes.const";
import { BOT_ROSTER } from "../lib/chess/bots/roster";

// The rows of «Jugar»'s catalogs and bots as SQL, for the migrations.
//
// Production never runs the seed, so catalog rows reach it inside a migration
// (as DatabaseKind did, 20260904190000_study_types_and_shares). This writes
// that SQL from the same constants and roster the seed reads, so the two can
// not drift: `npm run bots:sql` prints it to paste into a migration, and
// `play-catalog-sql.test.ts` checks the latest migration that carries it
// against what it prints now. A bot relabelled by the calibration is a new
// migration with this block, never an edit of an old one.
//
// Every insert is an upsert by code (or slug): it never touches `id`, nor a
// bot's `groupId`.

export const PLAY_CATALOG_BEGIN =
  "-- BEGIN play catalogs: generated by `npm run bots:sql` (prisma/play-catalog-sql.ts); do not edit by hand";
export const PLAY_CATALOG_END = "-- END play catalogs";

type SqlValue = string | number | boolean | null | { json: unknown } | { date: string } | { raw: string };

function literal(value: SqlValue): string {
  if (value === null) return "NULL";
  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return value ? "TRUE" : "FALSE";
  if (typeof value === "string") return `'${value.replaceAll("'", "''")}'`;
  if ("json" in value) return `${literal(JSON.stringify(value.json))}::jsonb`;
  if ("date" in value) return `${literal(value.date)}::date`;
  return value.raw;
}

function upsert(table: string, columns: string[], rows: SqlValue[][], conflict: string, update: string[]): string {
  const quoted = columns.map((column) => `"${column}"`).join(", ");
  const values = rows.map((row) => `  (${row.map(literal).join(", ")})`).join(",\n");
  const set = update.map((column) => `"${column}" = EXCLUDED."${column}"`).join(", ");
  return `INSERT INTO "${table}" (${quoted})\nVALUES\n${values}\nON CONFLICT ("${conflict}") DO UPDATE SET ${set};`;
}

/** The whole block: the three catalogs, then the bots. */
export function playCatalogSql(): string {
  const groups = upsert(
    "BotGroup",
    ["code", "label", "ring", "order"],
    Object.values(BOT_GROUP)
      .filter((code) => BOT_GROUP_LISTED[code])
      .map((code, order) => [code, BOT_GROUP_LABELS[code], BOT_GROUP_RING[code], order]),
    "code",
    ["label", "ring", "order"],
  );

  const timeControls = upsert(
    "TimeControl",
    ["code", "label", "initialSeconds", "incrementSeconds", "order", "isActive"],
    TIME_CONTROL_VALUES.map((row, order) => [
      row.code,
      row.label,
      row.initialSeconds,
      row.incrementSeconds,
      order,
      row.isActive,
    ]),
    "code",
    ["label", "initialSeconds", "incrementSeconds", "order", "isActive"],
  );

  const terminations = upsert(
    "GameTermination",
    ["code", "label", "order"],
    Object.values(GAME_TERMINATION).map((code, order) => [code, GAME_TERMINATION_LABELS[code], order]),
    "code",
    ["label", "order"],
  );

  const bots = upsert(
    "Bot",
    [
      "slug",
      "name",
      "elo",
      "bio",
      "openings",
      "fideElo",
      "fideTitle",
      "country",
      "ratingAsOf",
      "groupId",
      "order",
      "isActive",
    ],
    BOT_ROSTER.map((bot) => [
      bot.slug,
      bot.name,
      bot.elo,
      bot.bio,
      { json: bot.openings },
      bot.fideElo,
      bot.fideTitle,
      bot.country,
      bot.ratingAsOf ? { date: bot.ratingAsOf } : null,
      { raw: `(SELECT "id" FROM "BotGroup" WHERE "code" = ${literal(bot.group)})` },
      bot.order,
      bot.isActive,
    ]),
    "slug",
    ["name", "elo", "bio", "openings", "fideElo", "fideTitle", "country", "ratingAsOf", "order", "isActive"],
  );

  return [PLAY_CATALOG_BEGIN, groups, timeControls, terminations, bots, PLAY_CATALOG_END].join("\n\n");
}
